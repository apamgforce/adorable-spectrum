CREATE DATABASE IF NOT EXISTS dunewood_school CHARACTER SET utf8mb4;
USE dunewood_school;
CREATE TABLE IF NOT EXISTS `teachers` (
  `id` VARCHAR(16) PRIMARY KEY,
  `name` VARCHAR(255) NOT NULL DEFAULT '',
  `subject` VARCHAR(255) NOT NULL DEFAULT '',
  `phone` VARCHAR(255) NOT NULL DEFAULT '',
  `email` VARCHAR(255) NOT NULL DEFAULT '',
  `salary` INT NOT NULL DEFAULT 0,
  `status` VARCHAR(255) NOT NULL DEFAULT ''
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS `classes` (
  `id` VARCHAR(16) PRIMARY KEY,
  `name` VARCHAR(255) NOT NULL DEFAULT '',
  `teacherId` VARCHAR(255) NOT NULL DEFAULT '',
  `room` VARCHAR(255) NOT NULL DEFAULT '',
  `capacity` INT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS `students` (
  `id` VARCHAR(16) PRIMARY KEY,
  `name` VARCHAR(255) NOT NULL DEFAULT '',
  `classId` VARCHAR(255) NOT NULL DEFAULT '',
  `gender` VARCHAR(255) NOT NULL DEFAULT '',
  `dob` VARCHAR(255) NOT NULL DEFAULT '',
  `guardian` VARCHAR(255) NOT NULL DEFAULT '',
  `phone` VARCHAR(255) NOT NULL DEFAULT '',
  `address` VARCHAR(255) NOT NULL DEFAULT '',
  `status` VARCHAR(255) NOT NULL DEFAULT ''
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS `exams` (
  `id` VARCHAR(16) PRIMARY KEY,
  `name` VARCHAR(255) NOT NULL DEFAULT '',
  `date` VARCHAR(255) NOT NULL DEFAULT ''
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS `grades` (
  `id` VARCHAR(16) PRIMARY KEY,
  `studentId` VARCHAR(255) NOT NULL DEFAULT '',
  `examId` VARCHAR(255) NOT NULL DEFAULT '',
  `subject` VARCHAR(255) NOT NULL DEFAULT '',
  `score` INT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS `attendance` (
  `id` VARCHAR(16) PRIMARY KEY,
  `studentId` VARCHAR(255) NOT NULL DEFAULT '',
  `date` VARCHAR(255) NOT NULL DEFAULT '',
  `status` VARCHAR(255) NOT NULL DEFAULT ''
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS `fees` (
  `id` VARCHAR(16) PRIMARY KEY,
  `studentId` VARCHAR(255) NOT NULL DEFAULT '',
  `title` VARCHAR(255) NOT NULL DEFAULT '',
  `amount` INT NOT NULL DEFAULT 0,
  `paid` INT NOT NULL DEFAULT 0,
  `due` VARCHAR(255) NOT NULL DEFAULT ''
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS `books` (
  `id` VARCHAR(16) PRIMARY KEY,
  `title` VARCHAR(255) NOT NULL DEFAULT '',
  `author` VARCHAR(255) NOT NULL DEFAULT '',
  `copies` INT NOT NULL DEFAULT 0,
  `borrowedBy` VARCHAR(255) NOT NULL DEFAULT '',
  `due` VARCHAR(255) NOT NULL DEFAULT ''
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS `notices` (
  `id` VARCHAR(16) PRIMARY KEY,
  `title` VARCHAR(255) NOT NULL DEFAULT '',
  `date` VARCHAR(255) NOT NULL DEFAULT '',
  `body` TEXT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS `timetable` (
  `id` VARCHAR(16) PRIMARY KEY,
  `classId` VARCHAR(255) NOT NULL DEFAULT '',
  `day` VARCHAR(255) NOT NULL DEFAULT '',
  `period` INT NOT NULL DEFAULT 0,
  `subject` VARCHAR(255) NOT NULL DEFAULT ''
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS settings (k VARCHAR(50) PRIMARY KEY, v VARCHAR(255)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
